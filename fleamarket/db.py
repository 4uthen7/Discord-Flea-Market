"""永続化レイヤー（SQLite / PostgreSQL 両対応）。

DATABASE_URL に postgres:// を指定すると PostgreSQL、それ以外はローカルの SQLite を使う。
Render の無料プランなどディスクが消える環境では PostgreSQL（Neon など）を使うこと。

状態遷移はすべて「条件付き UPDATE」で行い、同時に2人が購入ボタンを
押した場合などでも二重取引にならないようにしている。
"""

from __future__ import annotations

import json
import sqlite3
from typing import Any, Optional

SCHEMA = """
CREATE TABLE IF NOT EXISTS guild_settings (
    guild_id          INTEGER PRIMARY KEY,
    market_channel_id INTEGER
);

CREATE TABLE IF NOT EXISTS listings (
    id          INTEGER PRIMARY KEY AUTOINCREMENT,
    guild_id    INTEGER NOT NULL,
    channel_id  INTEGER,
    message_id  INTEGER,
    seller_id   INTEGER NOT NULL,
    title       TEXT    NOT NULL,
    price       INTEGER NOT NULL,
    condition   TEXT    NOT NULL,
    description TEXT    NOT NULL DEFAULT '',
    images      TEXT    NOT NULL DEFAULT '[]',
    status      TEXT    NOT NULL DEFAULT 'open',   -- open / trading / sold / withdrawn
    created_at  TEXT    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS trades (
    id           INTEGER PRIMARY KEY AUTOINCREMENT,
    listing_id   INTEGER NOT NULL REFERENCES listings(id),
    seller_id    INTEGER NOT NULL,
    buyer_id     INTEGER NOT NULL,
    price        INTEGER NOT NULL,
    status       TEXT    NOT NULL DEFAULT 'requested', -- requested / page_sent / completed / cancelled
    trade_url    TEXT,
    created_at   TEXT    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TEXT
);

CREATE TABLE IF NOT EXISTS offers (
    id          INTEGER PRIMARY KEY AUTOINCREMENT,
    listing_id  INTEGER NOT NULL REFERENCES listings(id),
    buyer_id    INTEGER NOT NULL,
    price       INTEGER NOT NULL,
    message     TEXT    NOT NULL DEFAULT '',
    proposed_by TEXT    NOT NULL,                    -- buyer / seller
    status      TEXT    NOT NULL DEFAULT 'pending',  -- pending / accepted / rejected / countered / expired
    created_at  TEXT    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS ratings (
    id         INTEGER PRIMARY KEY AUTOINCREMENT,
    trade_id   INTEGER NOT NULL REFERENCES trades(id),
    rater_id   INTEGER NOT NULL,
    ratee_id   INTEGER NOT NULL,
    ratee_role TEXT    NOT NULL,                     -- seller / buyer（評価された側の立場）
    score      INTEGER NOT NULL CHECK (score BETWEEN 1 AND 5),
    comment    TEXT    NOT NULL DEFAULT '',
    created_at TEXT    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (trade_id, rater_id)
);

CREATE INDEX IF NOT EXISTS idx_ratings_ratee ON ratings (ratee_id);
CREATE INDEX IF NOT EXISTS idx_trades_listing ON trades (listing_id);
"""

PG_NOW = "to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')"


def _postgres_schema() -> str:
    # Discord の ID は 32bit に収まらないので BIGINT にする
    return (
        SCHEMA.replace("INTEGER PRIMARY KEY AUTOINCREMENT", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
        .replace("INTEGER", "BIGINT")
        .replace("CURRENT_TIMESTAMP", f"({PG_NOW})")
    )


class _Result:
    def __init__(self, rows: list[Any], rowcount: int) -> None:
        self._rows = rows
        self.rowcount = rowcount

    def fetchone(self) -> Any:
        return self._rows[0] if self._rows else None

    def fetchall(self) -> list[Any]:
        return self._rows


class _PostgresConnection:
    """sqlite3.Connection と同じ書き方（`with conn:` と `conn.execute`）で PostgreSQL を使うための薄いラッパー。"""

    def __init__(self, url: str) -> None:
        from psycopg.rows import dict_row
        from psycopg_pool import ConnectionPool

        # 無料DBはしばらく使わないと接続が切れるので、取り出すたびに生存確認する
        self.pool = ConnectionPool(
            url,
            min_size=1,
            max_size=2,
            kwargs={"autocommit": True, "row_factory": dict_row},
            check=ConnectionPool.check_connection,
            open=True,
        )
        self._conn: Any = None
        self._stack: list[Any] = []

    def __enter__(self) -> "_PostgresConnection":
        conn_cm = self.pool.connection()
        conn = conn_cm.__enter__()
        tx = conn.transaction()
        tx.__enter__()
        self._stack = [conn_cm, tx]
        self._conn = conn
        return self

    def __exit__(self, *exc: Any) -> None:
        conn_cm, tx = self._stack
        self._conn = None
        self._stack = []
        try:
            tx.__exit__(*exc)
        finally:
            conn_cm.__exit__(*exc)

    def execute(self, sql: str, params: tuple = ()) -> _Result:
        sql = sql.replace("?", "%s")
        if self._conn is not None:
            return self._run(self._conn, sql, params)
        with self.pool.connection() as conn:
            return self._run(conn, sql, params)

    @staticmethod
    def _run(conn: Any, sql: str, params: tuple) -> _Result:
        cur = conn.execute(sql, params)
        return _Result(cur.fetchall() if cur.description else [], cur.rowcount)


class Database:
    def __init__(self, url: str) -> None:
        self.is_postgres = url.startswith(("postgres://", "postgresql://"))
        self.conn: Any
        if self.is_postgres:
            self.conn = _PostgresConnection(url)
            self.now_sql = PG_NOW
            self.integrity_errors: tuple[type[Exception], ...] = (__import__("psycopg").IntegrityError,)
            with self.conn:
                for statement in _postgres_schema().split(";"):
                    if statement.strip():
                        self.conn.execute(statement)
        else:
            self.conn = sqlite3.connect(url)
            self.conn.row_factory = sqlite3.Row
            self.conn.execute("PRAGMA foreign_keys = ON")
            self.conn.executescript(SCHEMA)
            self.now_sql = "CURRENT_TIMESTAMP"
            self.integrity_errors = (sqlite3.IntegrityError,)

    def _one(self, sql: str, params: tuple = ()) -> Optional[Any]:
        return self.conn.execute(sql, params).fetchone()

    def _all(self, sql: str, params: tuple = ()) -> list[Any]:
        return self.conn.execute(sql, params).fetchall()

    # ---------------------------------------------------------------- settings
    def get_market_channel(self, guild_id: int) -> Optional[int]:
        row = self._one("SELECT market_channel_id FROM guild_settings WHERE guild_id = ?", (guild_id,))
        return row["market_channel_id"] if row else None

    def set_market_channel(self, guild_id: int, channel_id: int) -> None:
        with self.conn:
            self.conn.execute(
                "INSERT INTO guild_settings (guild_id, market_channel_id) VALUES (?, ?) "
                "ON CONFLICT(guild_id) DO UPDATE SET market_channel_id = excluded.market_channel_id",
                (guild_id, channel_id),
            )

    # ---------------------------------------------------------------- listings
    def create_listing(
        self,
        *,
        guild_id: int,
        seller_id: int,
        title: str,
        price: int,
        condition: str,
        description: str,
        images: list[str],
    ) -> int:
        with self.conn:
            cur = self.conn.execute(
                "INSERT INTO listings (guild_id, seller_id, title, price, condition, description, images) "
                "VALUES (?, ?, ?, ?, ?, ?, ?) RETURNING id",
                (guild_id, seller_id, title, price, condition, description, json.dumps(images)),
            )
            return int(cur.fetchone()["id"])

    def delete_listing(self, listing_id: int) -> None:
        with self.conn:
            self.conn.execute("DELETE FROM listings WHERE id = ?", (listing_id,))

    def set_listing_message(self, listing_id: int, channel_id: int, message_id: int) -> None:
        with self.conn:
            self.conn.execute(
                "UPDATE listings SET channel_id = ?, message_id = ? WHERE id = ?",
                (channel_id, message_id, listing_id),
            )

    def get_listing(self, listing_id: int) -> Optional[dict[str, Any]]:
        row = self._one("SELECT * FROM listings WHERE id = ?", (listing_id,))
        if row is None:
            return None
        listing = dict(row)
        listing["images"] = json.loads(listing["images"])
        return listing

    def update_listing(self, listing_id: int, *, title: str, price: int, condition: str, description: str) -> bool:
        with self.conn:
            cur = self.conn.execute(
                "UPDATE listings SET title = ?, price = ?, condition = ?, description = ? "
                "WHERE id = ? AND status = 'open'",
                (title, price, condition, description, listing_id),
            )
        return cur.rowcount == 1

    def withdraw_listing(self, listing_id: int) -> bool:
        with self.conn:
            cur = self.conn.execute(
                "UPDATE listings SET status = 'withdrawn' WHERE id = ? AND status = 'open'", (listing_id,)
            )
            if cur.rowcount == 1:
                self.conn.execute(
                    "UPDATE offers SET status = 'expired' WHERE listing_id = ? AND status = 'pending'",
                    (listing_id,),
                )
        return cur.rowcount == 1

    def listings_by_seller(self, seller_id: int, statuses: tuple[str, ...]) -> list[Any]:
        marks = ",".join("?" * len(statuses))
        return self._all(
            f"SELECT * FROM listings WHERE seller_id = ? AND status IN ({marks}) ORDER BY id DESC",
            (seller_id, *statuses),
        )

    # ------------------------------------------------------------------ trades
    def start_trade(self, listing_id: int, buyer_id: int, price: int, accepted_offer_id: Optional[int] = None) -> Optional[int]:
        """出品を「取引中」にして取引を作成する。既に売れていたら None。"""
        with self.conn:
            cur = self.conn.execute(
                "UPDATE listings SET status = 'trading' WHERE id = ? AND status = 'open' AND seller_id != ?",
                (listing_id, buyer_id),
            )
            if cur.rowcount != 1:
                return None
            seller_id = self._one("SELECT seller_id FROM listings WHERE id = ?", (listing_id,))["seller_id"]
            cur = self.conn.execute(
                "INSERT INTO trades (listing_id, seller_id, buyer_id, price) VALUES (?, ?, ?, ?) RETURNING id",
                (listing_id, seller_id, buyer_id, price),
            )
            trade_id = int(cur.fetchone()["id"])
            # 取引が始まったら、ほかの交渉はすべて無効にする
            self.conn.execute(
                "UPDATE offers SET status = 'expired' WHERE listing_id = ? AND status = 'pending' AND id != ?",
                (listing_id, accepted_offer_id or 0),
            )
        return trade_id

    def get_trade(self, trade_id: int) -> Optional[Any]:
        return self._one("SELECT * FROM trades WHERE id = ?", (trade_id,))

    def set_trade_url(self, trade_id: int, url: str) -> bool:
        with self.conn:
            cur = self.conn.execute(
                "UPDATE trades SET trade_url = ?, status = 'page_sent' WHERE id = ? AND status IN ('requested', 'page_sent')",
                (url, trade_id),
            )
        return cur.rowcount == 1

    def complete_trade(self, trade_id: int) -> bool:
        with self.conn:
            cur = self.conn.execute(
                f"UPDATE trades SET status = 'completed', completed_at = {self.now_sql} "
                "WHERE id = ? AND status = 'page_sent'",
                (trade_id,),
            )
            if cur.rowcount == 1:
                self.conn.execute(
                    "UPDATE listings SET status = 'sold' WHERE id = (SELECT listing_id FROM trades WHERE id = ?)",
                    (trade_id,),
                )
        return cur.rowcount == 1

    def cancel_trade(self, trade_id: int) -> bool:
        with self.conn:
            cur = self.conn.execute(
                "UPDATE trades SET status = 'cancelled' WHERE id = ? AND status IN ('requested', 'page_sent')",
                (trade_id,),
            )
            if cur.rowcount == 1:
                self.conn.execute(
                    "UPDATE listings SET status = 'open' "
                    "WHERE id = (SELECT listing_id FROM trades WHERE id = ?) AND status = 'trading'",
                    (trade_id,),
                )
        return cur.rowcount == 1

    def active_trades_for_user(self, user_id: int) -> list[Any]:
        return self._all(
            "SELECT t.*, l.title FROM trades t JOIN listings l ON l.id = t.listing_id "
            "WHERE (t.seller_id = ? OR t.buyer_id = ?) AND t.status IN ('requested', 'page_sent') "
            "ORDER BY t.id DESC",
            (user_id, user_id),
        )

    # ------------------------------------------------------------------ offers
    def create_offer(self, listing_id: int, buyer_id: int, price: int, message: str, proposed_by: str) -> int:
        with self.conn:
            # 同じ購入希望者からの古い交渉は、新しい提案で置き換える
            self.conn.execute(
                "UPDATE offers SET status = 'expired' WHERE listing_id = ? AND buyer_id = ? AND status = 'pending'",
                (listing_id, buyer_id),
            )
            cur = self.conn.execute(
                "INSERT INTO offers (listing_id, buyer_id, price, message, proposed_by) VALUES (?, ?, ?, ?, ?) RETURNING id",
                (listing_id, buyer_id, price, message, proposed_by),
            )
            return int(cur.fetchone()["id"])

    def get_offer(self, offer_id: int) -> Optional[Any]:
        return self._one("SELECT * FROM offers WHERE id = ?", (offer_id,))

    def resolve_offer(self, offer_id: int, status: str) -> bool:
        """保留中の交渉を accepted / rejected / countered にする。"""
        with self.conn:
            cur = self.conn.execute(
                "UPDATE offers SET status = ? WHERE id = ? AND status = 'pending'", (status, offer_id)
            )
        return cur.rowcount == 1

    # ----------------------------------------------------------------- ratings
    def add_rating(self, *, trade_id: int, rater_id: int, ratee_id: int, ratee_role: str, score: int, comment: str) -> bool:
        try:
            with self.conn:
                self.conn.execute(
                    "INSERT INTO ratings (trade_id, rater_id, ratee_id, ratee_role, score, comment) "
                    "VALUES (?, ?, ?, ?, ?, ?)",
                    (trade_id, rater_id, ratee_id, ratee_role, score, comment),
                )
        except self.integrity_errors:
            return False
        return True

    def has_rated(self, trade_id: int, rater_id: int) -> bool:
        return self._one("SELECT 1 FROM ratings WHERE trade_id = ? AND rater_id = ?", (trade_id, rater_id)) is not None

    def rating_summary(self, user_id: int, guild_id: Optional[int] = None) -> dict[str, Any]:
        """評価の集計。guild_id を渡すとそのサーバーでの取引だけに絞る（他サーバーの評価は見せない）。"""
        guild_sql, guild_params = ("", ()) if guild_id is None else (" AND l.guild_id = ?", (guild_id,))
        rating_from = (
            "FROM ratings r JOIN trades t ON t.id = r.trade_id JOIN listings l ON l.id = t.listing_id "
            "WHERE r.ratee_id = ?" + guild_sql
        )

        def agg(role: Optional[str]) -> tuple[Optional[float], int]:
            role_sql, role_params = ("", ()) if role is None else (" AND r.ratee_role = ?", (role,))
            row = self._one(
                f"SELECT AVG(r.score) a, COUNT(*) c {rating_from}{role_sql}", (user_id, *guild_params, *role_params)
            )
            return (float(row["a"]) if row["a"] is not None else None), int(row["c"])

        def count_trades(column: str) -> int:
            return int(
                self._one(
                    "SELECT COUNT(*) c FROM trades t JOIN listings l ON l.id = t.listing_id "
                    f"WHERE t.{column} = ? AND t.status = 'completed'{guild_sql}",
                    (user_id, *guild_params),
                )["c"]
            )

        overall_avg, overall_count = agg(None)
        seller_avg, seller_count = agg("seller")
        buyer_avg, buyer_count = agg("buyer")
        open_listings = self._one(
            f"SELECT COUNT(*) c FROM listings l WHERE l.seller_id = ? AND l.status = 'open'{guild_sql}",
            (user_id, *guild_params),
        )["c"]
        return {
            "avg": overall_avg,
            "count": overall_count,
            "seller_avg": seller_avg,
            "seller_count": seller_count,
            "buyer_avg": buyer_avg,
            "buyer_count": buyer_count,
            "sold": count_trades("seller_id"),
            "bought": count_trades("buyer_id"),
            "open_listings": int(open_listings),
        }

    def recent_ratings(self, user_id: int, guild_id: Optional[int] = None, limit: int = 5) -> list[Any]:
        guild_sql, guild_params = ("", ()) if guild_id is None else (" AND l.guild_id = ?", (guild_id,))
        return self._all(
            "SELECT r.*, l.title FROM ratings r "
            "JOIN trades t ON t.id = r.trade_id JOIN listings l ON l.id = t.listing_id "
            f"WHERE r.ratee_id = ?{guild_sql} ORDER BY r.id DESC LIMIT ?",
            (user_id, *guild_params, limit),
        )
